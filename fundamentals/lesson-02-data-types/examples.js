// Lesson 02 - Data Types (Examples)
// =======================================

// Number
const age = 21;
console.log(age);
console.log(typeof age);

// String
const name = "Ammar";
console.log(name);
console.log(typeof name);

// Boolean
const isStudent = true;
console.log(isStudent);
console.log(typeof isStudent);

// Undefined
let city;
console.log(city);
console.log(typeof city);

// Null
const address = null;
console.log(address);
console.log(typeof address);

// Object
const student = {
    name: "Ammar",
    semester: 4
};

console.log(student);
console.log(typeof student);

// Array
const marks = [78, 90, 66];
console.log(marks);
console.log(typeof marks);

// Function
function greet() {
    console.log("Hello!");
}

console.log(typeof greet);