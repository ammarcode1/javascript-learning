// let -> Value can be changed
let age = 21;
console.log(age);

age = 22;
console.log(age);

// const -> Value cannot be reassigned
const university = "UCP";
console.log(university);

// Template Literals (`` This is called backticks) and template literals are used to create strings that can contain variables and expressions.
const name = "Ammar";
console.log(`My name is ${name}.`);