// Lesson 03 - Operators

// Arithmetic Operators

console.log(10 + 5);
console.log(10 - 5);
console.log(10 * 5);
console.log(10 / 5);
console.log(10 % 3);

// Comparison Operators

console.log(10 > 5);
console.log(10 < 5);
console.log(10 >= 10);
console.log(10 <= 8);

// Equality Operators

console.log(10 == "10");
console.log(10 === "10");

console.log(10 != "10");
console.log(10 !== "10");

// Logical Operators

console.log(true && true);
console.log(true && false);

console.log(true || false);
console.log(false || false);

console.log(!true);
console.log(!false);

// Assignment Operators

let number = 10;

number += 5;
console.log(number);

number -= 3;
console.log(number);

number *= 2;
console.log(number);

number /= 4;
console.log(number);

// String Concatenation

console.log("Hello " + "Ammar");
console.log("Age: " + 21);

// Type Coercion

console.log(4 + "6");    // "46"
console.log(4 - "6");    // -2
console.log(4 * "6");    // 24
console.log(4 / "2");    // 2
console.log(true + 1);   // 2
console.log(false + 1);  // 1